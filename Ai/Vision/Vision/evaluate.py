"""Detection mAP plus class-aware IoU-matched weight MAE (reports coverage)."""
import argparse
import json
from pathlib import Path
import yaml
from food_ai import ROOT, DEFAULT_MODEL, load_model, predict

def iou(a, b):
    intersection = max(0, min(a[2], b[2]) - max(a[0], b[0])) * max(0, min(a[3], b[3]) - max(a[1], b[1]))
    union = (a[2]-a[0]) * (a[3]-a[1]) + (b[2]-b[0]) * (b[3]-b[1]) - intersection
    return intersection / union if union > 0 else 0.

def weight_errors(foods, targets, threshold=.5):
    used, errors = set(), []
    for food in sorted(foods, key=lambda f: f['confidence'], reverse=True):
        candidates = [(iou(food['bbox_normalized_xyxy'], t['box']), i) for i, t in enumerate(targets)
                      if i not in used and t['class_id'] == food['class_id']]
        overlap, index = max(candidates, default=(0., -1))
        if overlap >= threshold:
            used.add(index)
            if food['weight_g'] is not None and targets[index]['weight'] > 0:
                errors.append(abs(food['weight_g'] - targets[index]['weight']))
    return errors, len(used)

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--data', type=Path, default=ROOT / 'data_full.yaml')
    p.add_argument('--model', type=Path, default=DEFAULT_MODEL)
    p.add_argument('--device', default='0')
    p.add_argument('--output', type=Path, default=ROOT / 'outputs' / 'evaluation.json')
    args = p.parse_args()
    cfg = yaml.safe_load(args.data.read_text(encoding='utf-8'))
    manifest = Path(cfg['val'])
    if not manifest.is_file() or manifest.suffix != '.txt':
        p.error('Expected a validation image manifest, as generated by download.py')
    model = load_model(args.model)
    metrics = model.val(data=str(args.data.resolve()), device=args.device, batch=2, workers=0, plots=False,
                        project=str(ROOT / 'runs'), name='evaluation')
    errors, matched, total = [], 0, 0
    for name in manifest.read_text(encoding='utf-8').splitlines():
        path = Path(name)
        label = path.parent.parent / 'labels' / (path.stem + '.txt')
        targets = []
        for row in label.read_text().splitlines():
            c, x, y, w, h, grams = map(float, row.split())
            targets.append({'class_id': int(c), 'box': [x-w/2, y-h/2, x+w/2, y+h/2], 'weight': grams})
        payload, _ = predict(model, path, args.device)
        new_errors, count = weight_errors(payload['foods'], targets)
        errors.extend(new_errors)
        matched += count
        total += len(targets)
    report = {'map50': float(metrics.box.map50), 'map50_95': float(metrics.box.map),
              'weight_mae_g_matched_only': sum(errors) / len(errors) if errors else None,
              'weight_pairs': len(errors), 'matched_boxes': matched, 'ground_truth_boxes': total,
              'matching_iou': .5, 'weight_detection_confidence': .35,
              'note': 'Weight MAE excludes missed/misclassified objects; read together with detection coverage. Sample data is not a benchmark.'}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2), encoding='utf-8')
    print(json.dumps(report, indent=2))

if __name__ == '__main__':
    main()
